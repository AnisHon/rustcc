use crate::source::SourceRange;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Punctuator {
    LBracket,
    RBracket,
    LParen,
    RParen,
    LBrace,
    RBrace,
    Dot,
    Arrow,
    Inc,
    Dec,
    Amp,
    Star,
    Plus,
    Minus,
    Tilde,
    Bang,
    Slash,
    Percent,
    Shl,
    Shr,
    Lt,
    Gt,
    Le,
    Ge,
    Eq,
    Ne,
    Caret,
    Pipe,
    And,
    Or,
    Question,
    Colon,
    Semi,
    Ellipsis,
    Assign,
    StarEq,
    SlashEq,
    PercentEq,
    PlusEq,
    MinusEq,
    ShlEq,
    ShrEq,
    AmpEq,
    CaretEq,
    PipeEq,
    Comma,
    Hash,
    HashHash,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PPTokenKind {
    Invalid,
    Identifier,
    Number,
    Character,
    String,
    Punctuator(Punctuator),
    NewLine,
    EndOfFile,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PPToken {
    pub kind: PPTokenKind,
    pub spelling: String,
    pub range: SourceRange,
    pub leading_space: bool,
    pub start_of_line: bool,
}
